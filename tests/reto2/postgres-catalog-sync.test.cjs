'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const {randomUUID,randomBytes}=require('node:crypto');
const {execFileSync}=require('node:child_process');

test('PostgreSQL temporal incorpora las 48 referencias reales una vez y conserva ediciones comerciales',{skip:!process.env.PHARMACY_TEST_DATABASE_URL,timeout:120000},async t=>{
 const root=path.resolve(__dirname,'../..');
 const url=new URL(process.env.PHARMACY_TEST_DATABASE_URL);
 const metadata=JSON.parse(fs.readFileSync(process.env.PHARMACY_TEST_POSTGRES_META,'utf8'));
 assert.equal(url.hostname,'127.0.0.1');assert.equal(url.port,String(metadata.port));
 assert.equal(url.username,'farmacia_test');assert.equal(url.password,'');assert.equal(url.pathname,'/farmacia_test');
 const {PrismaClient}=require('../../node_modules/.prisma-farmacia-postgresql');
 const control=new PrismaClient({datasources:{db:{url:url.href}}});
 const database='farmacia_test_catalogo_'+randomUUID().replaceAll('-','');
 assert.match(database,/^farmacia_test_catalogo_[a-f0-9]{32}$/);
 await control.$executeRawUnsafe('CREATE DATABASE "'+database+'"');
 url.pathname='/'+database;
 const directory=fs.mkdtempSync(path.join(os.tmpdir(),'farmacia-pg-catalogo-'));
 let db;
 t.after(async()=>{
  if(db)await db.$disconnect();
  await control.$executeRawUnsafe('DROP DATABASE "'+database+'"');
  await control.$disconnect();
  assert.ok(path.resolve(directory).startsWith(path.resolve(os.tmpdir())+path.sep+'farmacia-pg-catalogo-'));
  fs.rmSync(directory,{recursive:true,force:true});
 });
 const env={};
 for(const key of ['SystemRoot','PATH','Path','TEMP','TMP','USERPROFILE','LOCALAPPDATA','NODE_OPTIONS'])if(process.env[key])env[key]=process.env[key];
 Object.assign(env,{NODE_ENV:'test',DATABASE_URL:url.href,ADMIN_EMAIL:'pg-catalogo@example.ec',ADMIN_PASSWORD:'SyntheticCatalog2026!',JWT_SECRET:randomBytes(48).toString('hex'),CORS_ORIGIN:'http://localhost:3000',IMAGE_STORAGE:'local',UPLOAD_DIR:path.join(directory,'uploads'),EMAIL_VERIFICATION_ENABLED:'false',CUSTOMER_REGISTRATION_REQUIRE_EMAIL:'false'});
 const source=path.join(root,'server/prisma/postgresql'),schema=path.join(directory,'schema.prisma');
 fs.copyFileSync(path.join(source,'schema.prisma'),schema);
 fs.cpSync(path.join(source,'migrations'),path.join(directory,'migrations'),{recursive:true});
 execFileSync(process.execPath,[path.join(root,'node_modules/prisma/build/index.js'),'migrate','deploy','--schema',schema],{cwd:directory,env,stdio:'pipe',windowsHide:true});
 execFileSync(process.execPath,[path.join(root,'server/prisma/seed.cjs')],{cwd:root,env,stdio:'pipe',windowsHide:true});
 Object.assign(process.env,env);
 db=new PrismaClient({datasources:{db:{url:url.href}}});
 assert.equal(await db.producto.count(),18);
 assert.ok(await db.semilla.findUnique({where:{id:'catalogo-inicial-v1'}}));
 const future=new Date(Date.now()+60000);
 await db.producto.update({where:{id:'solar'},data:{precio:13.37,stock:7,updatedAt:future}});
 const {syncCatalog}=require('../../scripts/sync-catalog.cjs');
 const result=await syncCatalog({db});
 assert.deepEqual(result,{version:'catalogo-secciones-v1',created:48,reclassified:13,skipped:false});
 assert.equal(await db.producto.count(),66);
 assert.equal(await db.producto.count({where:{soloConsulta:true,precio:0,stock:0}}),48);
 const legacy=await db.producto.findUnique({where:{id:'solar'}});
 assert.equal(legacy.categoria,'proteccion-solar');assert.equal(Number(legacy.precio),13.37);assert.equal(legacy.stock,7);assert.ok(legacy.updatedAt>future);
 const medications=await db.producto.findMany({where:{tipoProducto:'medicamento'}});
 assert.equal(medications.length,4);
 assert.ok(medications.every(product=>product.soloConsulta&&product.registroSanitario&&product.principioActivo&&product.concentracion&&product.pvpMaximo===null&&product.ivaCategoria==='cero'));
 const groups=await db.producto.groupBy({by:['categoria'],where:{activo:true},_count:{_all:true}});
 assert.equal(groups.length,16);assert.ok(groups.every(group=>group._count._all>=2));
 const editable=await db.producto.findFirst({where:{soloConsulta:true,tipoProducto:'cuidado'}});
 await db.producto.update({where:{id:editable.id},data:{nombre:'Ficha editada por la farmacia',soloConsulta:false,precio:19.75,stock:6}});
 const repeated=await Promise.all([syncCatalog({db}),syncCatalog({db})]);
 assert.ok(repeated.every(value=>value.skipped&&value.created===0&&value.reclassified===0));
 const preserved=await db.producto.findUnique({where:{id:editable.id}});
 assert.equal(preserved.nombre,'Ficha editada por la farmacia');assert.equal(preserved.soloConsulta,false);assert.equal(Number(preserved.precio),19.75);assert.equal(preserved.stock,6);
 assert.equal(await db.producto.count(),66);assert.equal(await db.semilla.count({where:{id:'catalogo-secciones-v1'}}),1);
 t.diagnostic('48 referencias reales, 13 reclasificaciones y 66 productos en base PostgreSQL temporal.');
});
